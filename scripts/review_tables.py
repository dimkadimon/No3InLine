#!/usr/bin/env python3
"""Separate analytical / coordinate-backed benchmarks from unverified reports.

The comparison algorithm and its R2 data and golden files are immutable inputs.
With --write, emit the current paper fragments and the two-tier CSV. Otherwise
compare them byte for byte. No restored upstream coordinates or network needed.
"""
import argparse
import csv
import io
from pathlib import Path
from unittest.mock import patch

import comparison as old

ROOT = Path(__file__).resolve().parents[1]
RING = {293, 389, 773, 4037, 10085, 13445, 16805, 3188645}
CITES = {'kiro_conic 2026-10-09': 'chain', 'kiro_c1_collinear 2026-10-07': 'plateau',
         'kiro_c1_collinear 2026-10-16': 'framepost'}


def generate(write=False):
    with (ROOT / 'results/lower-bounds.csv').open() as f:
        historical = {int(r['n']): r for r in csv.DictReader(f)}
    with patch.object(old, 'REPORTS', ()):  # exact same maximization, excluding the F family
        checked = {n: old.benchmarks(n) for n in old.sides}
    buf = io.StringIO(newline='')
    w = csv.writer(buf, lineterminator='\n')
    w.writerow(['n', 'B_checked', 'source_codes', 'benchmark_details', 'certified_count', 'symmetry',
                'delta_vs_checked', 'excess_vs_1.5n', 'certificate_or_coordinates', 'report_source_side',
                'report_source_count', 'report_transfer', 'delta_vs_report', 'report_url'])
    ring, other, reports = [], [], []
    for n in old.sides:
        v, sym, path = old.project(n)
        mx, bs = checked[n]
        codes = ','.join(sorted({b[1] for b in bs}))
        h = historical[n]
        assert 'F' not in codes and v == int(h['certified_count']) and sym == h['symmetry']
        twice = 2*v - 3*n
        assert twice >= 0
        excess = str(twice//2) + ('.5' if twice % 2 else '')
        assert excess == h['excess_vs_1.5n']
        delta = v - mx
        fmt = old.fmt
        delta_tex = (' +' if delta > 0 else '') + fmt(delta)
        ex_tex = fmt(twice//2) + ('.5' if twice % 2 else '')
        row = f'{fmt(n)} & {fmt(mx)} & {codes} & {fmt(v)} & {sym} & ${delta_tex}$ & $+{ex_tex}$ ' + r'\\'
        (ring if n in RING else other).append(row)
        ref, _ = old.benchmarks(n)
        assert ref == int(h['B_ref']) and ref >= mx
        fields = [''] * 5
        if ref > mx:
            wins = [(a, b, z) for z in old.REPORTS for a, b in [(int(z['side']), int(z['points']))]
                    if b - 4*max(a-n, 0) == ref]
            assert len(wins) == 1 and h['source_codes'] == 'F'
            a, b, z = wins[0]
            fields = [a, b, ref, v-ref, z['source_url']]
            dtex = ('+' if v > ref else '') + fmt(v-ref)
            reports.append(f'{fmt(n)} & {fmt(a)} & ' + r'\reportcite{' + CITES[z['report']] +
                           f'}} & {fmt(b)} & {fmt(ref)} & {fmt(v)} & ${dtex}$ ' + r'\\')
        w.writerow([n, mx, codes, ' | '.join(b[2] for b in bs), v, sym, delta, excess, path, *fields])
    assert len(reports) == 4 and len(ring) + len(other) == 15
    # Other-side rows can still be typeset from the unchanged kit output.
    assert (ROOT/'paper/table-other.tex').read_text().splitlines()[1:] == other
    header = '% Generated by scripts/review_tables.py; do not edit by hand.\n'
    files = {ROOT/'results/checked-comparisons.csv': buf.getvalue(),
             ROOT/'paper/table-checked-ring.tex': header + '\n'.join(ring) + '\n',
             ROOT/'paper/table-reports.tex': header + '\n'.join(reports) + '\n'}
    for path, text in files.items():
        if write:
            path.write_text(text)
        elif path.read_bytes() != text.encode():
            raise ValueError(f'Output differs: {path}')
    print('PASS: 15 analytic/coordinate-backed comparisons; four stronger report-only transfers separately. All witnesses and both negative report differences retained.')


if __name__ == '__main__':
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--write', action='store_true')
    generate(ap.parse_args().write)
